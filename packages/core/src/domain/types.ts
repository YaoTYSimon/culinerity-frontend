import type { CulturalMeal, FoodProfile } from '../food/types';
import type { PantryState, ShoppingEntry } from '../pantry/types';
import type { TradeoffEntry } from '../tradeoffs/types';

/** Australian dollars. */
export type Aud = number;

/** One completed check-in. `at` is an ISO date string. */
export interface ScoreEntry {
  score: number;
  at: string;
}

/** One "added to my week" swap. `saving` is AUD per serve as computed at add time. */
export interface WeekSwap {
  itemId: string;
  name: string;
  saving: Aud;
  at: string;
}

/** One logged food spend. `at` is an ISO date-time; `id` is generated by the app. */
export interface SpendEntry {
  id: string;
  amount: Aud;
  category: 'groceries' | 'takeaway' | 'market' | 'other';
  note?: string;
  at: string;
}

export interface Profile {
  foodBudgetWeekly?: Aud;
  incomeWeekly?: Aud;
  suburb?: string;
  score?: number;
  scoreTakenAt?: string;
  welcomeSeen?: boolean;
  scoreHistory?: ScoreEntry[];
  weekSwaps?: WeekSwap[];
  spendEntries?: SpendEntry[];
  /** Optional, self-declared, device-only. Never sent to the server. */
  foodProfile?: FoodProfile;
  culturalMeals?: CulturalMeal[];
  /** Optional, self-declared, device-only. Absent when empty. */
  tradeoffs?: TradeoffEntry[];
  /** Optional, self-declared, device-only. Absent when empty. */
  pantry?: PantryState;
  shoppingList?: ShoppingEntry[];
}

export interface PricePoint {
  itemId: string;
  store: 'Coles' | 'Woolworths' | 'Aldi' | 'IGA' | 'Market';
  pricePerServe: Aud;
  unitLabel: string;
  observedAt: string;
  isSample: boolean;
}

export interface Nutrition {
  itemId: string;
  energyKj: number;
  proteinG: number;
  fibreG: number;
  sugarG: number;
  sodiumMg: number;
}

export interface FoodItem {
  id: string;
  name: string;
  category: string;
  keywords: string[];
}

export interface SwapCandidate {
  craving: FoodItem;
  alternative: FoodItem;
  note: string;
}

export interface SupportPlace {
  id: string;
  name: string;
  kind: 'pantry' | 'community-fridge' | 'meal';
  suburb: string;
  notes: string;
  isSample: boolean;
}
