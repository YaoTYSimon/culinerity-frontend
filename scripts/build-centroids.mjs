// Generates packages/core/src/places/generated/centroids.generated.ts
// from docs/superpowers/research/2026-10-27-melbourne-centroids.json.
// Run: npm run build:centroids
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const DATA_PATH = fileURLToPath(new URL('docs/superpowers/research/2026-10-27-melbourne-centroids.json', root));
export const OUT_PATH = fileURLToPath(new URL('packages/core/src/places/generated/centroids.generated.ts', root));

// Greater Melbourne box (same as the places dataset).
const LAT = [-38.6, -37.4];
const LNG = [144.3, 145.8];
const nonEmpty = (v) => typeof v === 'string' && v.trim() !== '';
const inRange = (v, [lo, hi]) => typeof v === 'number' && Number.isFinite(v) && v >= lo && v <= hi;
const inBox = (r) => inRange(r.lat, LAT) && inRange(r.lng, LNG);
// Mirrors normaliseName in packages/core/src/places/centroid.ts for duplicate detection.
const norm = (s) =>
  String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim();

/** Returns a list of problems; empty when the table is sound. */
export function validateCentroids(d) {
  const errs = [];
  const s = d.source ?? {};
  for (const k of ['publisher', 'title', 'licence', 'accessed']) if (!nonEmpty(s[k])) errs.push(`source ${k} is required`);
  if (typeof s.url !== 'string' || !s.url.startsWith('https://')) errs.push('source url must be https');
  const names = new Set();
  for (const r of d.suburbs ?? []) {
    if (!nonEmpty(r.name)) errs.push('suburb name is required');
    const n = norm(r.name);
    if (names.has(n)) errs.push(`duplicate suburb ${r.name}`);
    names.add(n);
    if (!inBox(r)) errs.push(`suburb ${r.name} is outside the Melbourne box`);
  }
  const codes = new Set();
  for (const r of d.postcodes ?? []) {
    if (typeof r.code !== 'string' || !/^\d{4}$/.test(r.code)) errs.push(`postcode ${r.code} must be 4 digits`);
    if (codes.has(r.code)) errs.push(`duplicate postcode ${r.code}`);
    codes.add(r.code);
    if (!nonEmpty(r.label)) errs.push(`postcode ${r.code} label is required`);
    if (!inBox(r)) errs.push(`postcode ${r.code} is outside the Melbourne box`);
  }
  return errs;
}

const row = (r) => `    ${JSON.stringify(r)}`;

export function buildCentroids(d) {
  const errs = validateCentroids(d);
  if (errs.length) throw new Error(`Invalid centroid table:\n- ${errs.join('\n- ')}`);
  return (
    '// GENERATED by scripts/build-centroids.mjs from docs/superpowers/research/2026-10-27-melbourne-centroids.json.\n' +
    '// Generated, do not edit by hand; run `npm run build:centroids`.\n' +
    "import type { CentroidTable } from '../centroid';\n\n" +
    'export const centroidTable: CentroidTable = {\n' +
    `  source: ${JSON.stringify(d.source)},\n` +
    `  suburbs: [\n${d.suburbs.map(row).join(',\n')},\n  ],\n` +
    `  postcodes: [\n${d.postcodes.map(row).join(',\n')},\n  ],\n};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT_PATH, buildCentroids(JSON.parse(readFileSync(DATA_PATH, 'utf8'))));
  console.log(`Wrote ${OUT_PATH}`);
}
